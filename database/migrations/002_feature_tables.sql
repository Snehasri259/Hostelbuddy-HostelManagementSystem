-- 002_feature_tables.sql: auth tokens, complaints, notices, notifications, guardians, visitors, outpasses
CREATE TABLE IF NOT EXISTS auth_tokens (
 token_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE,
 token_type ENUM('SET_PASSWORD','RESET_PASSWORD') NOT NULL,
 expires_at DATETIME NOT NULL,
 used_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_auth_tokens_user FOREIGN KEY (user_id) REFERENCES app_users(user_id) ON DELETE CASCADE,
 INDEX idx_auth_tokens_expiry(expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS complaints (
 complaint_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 student_id BIGINT UNSIGNED NOT NULL,
 block_id TINYINT UNSIGNED NOT NULL,
 subject VARCHAR(180) NOT NULL,
 category ENUM('MAINTENANCE','CLEANLINESS','ELECTRICAL','WATER','INTERNET','SAFETY','OTHER') NOT NULL DEFAULT 'OTHER',
 description TEXT NOT NULL,
 priority ENUM('LOW','MEDIUM','HIGH') NOT NULL DEFAULT 'MEDIUM',
 status ENUM('OPEN','IN_PROGRESS','RESOLVED','REJECTED') NOT NULL DEFAULT 'OPEN',
 response TEXT NULL,
 responded_by_user_id BIGINT UNSIGNED NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_complaint_student FOREIGN KEY(student_id) REFERENCES students(student_id),
 CONSTRAINT fk_complaint_block FOREIGN KEY(block_id) REFERENCES blocks(block_id),
 CONSTRAINT fk_complaint_responder FOREIGN KEY(responded_by_user_id) REFERENCES app_users(user_id),
 INDEX idx_complaint_block_status(block_id,status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notices (
 notice_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(180) NOT NULL,
 body TEXT NOT NULL,
 audience ENUM('ALL','BLOCK') NOT NULL DEFAULT 'ALL',
 block_id TINYINT UNSIGNED NULL,
 created_by_user_id BIGINT UNSIGNED NOT NULL,
 publish_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at DATETIME NULL,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_notice_block FOREIGN KEY(block_id) REFERENCES blocks(block_id),
 CONSTRAINT fk_notice_author FOREIGN KEY(created_by_user_id) REFERENCES app_users(user_id),
 CHECK ((audience='ALL' AND block_id IS NULL) OR (audience='BLOCK' AND block_id IS NOT NULL))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 notification_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(180) NOT NULL,
 message TEXT NOT NULL,
 notification_type VARCHAR(40) NOT NULL DEFAULT 'GENERAL',
 entity_type VARCHAR(40) NULL,
 entity_id VARCHAR(80) NULL,
 is_read BOOLEAN NOT NULL DEFAULT FALSE,
 email_status ENUM('NOT_CONFIGURED','PENDING','SENT','FAILED','PREVIEW') NOT NULL DEFAULT 'NOT_CONFIGURED',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 read_at DATETIME NULL,
 CONSTRAINT fk_notification_user FOREIGN KEY(user_id) REFERENCES app_users(user_id) ON DELETE CASCADE,
 INDEX idx_notifications_user_read(user_id,is_read,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS guardians (
 guardian_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 student_id BIGINT UNSIGNED NOT NULL,
 full_name VARCHAR(120) NOT NULL,
 relationship VARCHAR(40) NOT NULL,
 phone VARCHAR(20) NOT NULL,
 email VARCHAR(160) NULL,
 verification_status ENUM('PENDING','VERIFIED','REJECTED') NOT NULL DEFAULT 'PENDING',
 verified_by_user_id BIGINT UNSIGNED NULL,
 verified_at DATETIME NULL,
 verification_note VARCHAR(500) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_guardian_student FOREIGN KEY(student_id) REFERENCES students(student_id),
 CONSTRAINT fk_guardian_verifier FOREIGN KEY(verified_by_user_id) REFERENCES app_users(user_id),
 INDEX idx_guardian_status(verification_status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS visitor_requests (
 visitor_request_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 student_id BIGINT UNSIGNED NOT NULL,
 block_id TINYINT UNSIGNED NOT NULL,
 guardian_id BIGINT UNSIGNED NULL,
 visitor_name VARCHAR(120) NOT NULL,
 visitor_phone VARCHAR(20) NOT NULL,
 visitor_id_type VARCHAR(40) NULL,
 visitor_id_last4 CHAR(4) NULL,
 purpose VARCHAR(500) NOT NULL,
 visit_start DATETIME NOT NULL,
 visit_end DATETIME NULL,
 status ENUM('PENDING','APPROVED','REJECTED','CANCELLED','COMPLETED') NOT NULL DEFAULT 'PENDING',
 decided_by_user_id BIGINT UNSIGNED NULL,
 decided_at DATETIME NULL,
 decision_note VARCHAR(500) NULL,
 checked_in_at DATETIME NULL,
 checked_out_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_visitor_student FOREIGN KEY(student_id) REFERENCES students(student_id),
 CONSTRAINT fk_visitor_block FOREIGN KEY(block_id) REFERENCES blocks(block_id),
 CONSTRAINT fk_visitor_guardian FOREIGN KEY(guardian_id) REFERENCES guardians(guardian_id),
 CONSTRAINT fk_visitor_decider FOREIGN KEY(decided_by_user_id) REFERENCES app_users(user_id),
 INDEX idx_visitor_block_status(block_id,status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS outpasses (
 outpass_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 student_id BIGINT UNSIGNED NOT NULL,
 block_id TINYINT UNSIGNED NOT NULL,
 reason VARCHAR(500) NOT NULL,
 destination VARCHAR(250) NOT NULL,
 departure_time DATETIME NOT NULL,
 expected_return_time DATETIME NOT NULL,
 status ENUM('PENDING','APPROVED','REJECTED','CANCELLED','OUT','RETURNED','OVERDUE') NOT NULL DEFAULT 'PENDING',
 decided_by_user_id BIGINT UNSIGNED NULL,
 decided_at DATETIME NULL,
 decision_note VARCHAR(500) NULL,
 actual_departure_at DATETIME NULL,
 actual_return_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_outpass_student FOREIGN KEY(student_id) REFERENCES students(student_id),
 CONSTRAINT fk_outpass_block FOREIGN KEY(block_id) REFERENCES blocks(block_id),
 CONSTRAINT fk_outpass_decider FOREIGN KEY(decided_by_user_id) REFERENCES app_users(user_id),
 CHECK(expected_return_time > departure_time),
 INDEX idx_outpass_block_status(block_id,status)
) ENGINE=InnoDB;
