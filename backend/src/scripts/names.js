/** i-th student name for a gender. Unique per first name; girls only get girls' names, boys only boys'. */
export function studentName(gender, i) {
  const first = gender === 'BOY' ? BOY_FIRST : GIRL_FIRST;
  const r = i % first.length;
  const q = Math.floor(i / first.length);
  return `${first[r]} ${SURNAMES[(q * 7 + r * 3) % SURNAMES.length]}`;
}

const surnameOf = (fullName) => String(fullName).trim().split(/\s+/).slice(-1)[0];

/** Father is always a male name, mother a female name, both sharing the student's surname. */
export function parentNames(studentFullName, i) {
  const s = surnameOf(studentFullName);
  return { father: `${MALE_ADULT[(i * 5 + 3) % MALE_ADULT.length]} ${s}`, mother: `${FEMALE_ADULT[(i * 3 + 1) % FEMALE_ADULT.length]} ${s}` };
}

/** Visitor with a relationship; the name always matches the relationship's gender. */
export function visitorFor(studentFullName, i) {
  const s = surnameOf(studentFullName);
  const { father, mother } = parentNames(studentFullName, i);
  return [
    { rel: 'Father', name: father, purpose: 'Bringing documents and home food' },
    { rel: 'Mother', name: mother, purpose: 'Routine visit and to collect winter clothes' },
    { rel: 'Brother', name: `${BOY_FIRST[(i * 11 + 4) % BOY_FIRST.length]} ${s}`, purpose: 'Delivering a laptop charger' },
    { rel: 'Aunt', name: `${FEMALE_ADULT[(i * 7 + 5) % FEMALE_ADULT.length]} ${s}`, purpose: 'Family function invitation' },
    { rel: 'Uncle', name: `${MALE_ADULT[(i * 9 + 8) % MALE_ADULT.length]} ${s}`, purpose: 'Visiting while in the city for work' },
    { rel: 'Sister', name: `${GIRL_FIRST[(i * 13 + 2) % GIRL_FIRST.length]} ${s}`, purpose: 'Dropping books for exam preparation' },
  ][i % 6];
}

const CODE_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
/** Gate-pass code (8 chars, no look-alike characters). Real codes use crypto.randomBytes; this is for seeded demo rows. */
export function demoPassCode(seed) {
  let x = (seed * 2654435761) >>> 0; let out = '';
  for (let k = 0; k < 8; k++) { x = (Math.imul(x, 1664525) + 1013904223) >>> 0; out += CODE_ALPHABET[x % CODE_ALPHABET.length]; }
  return out;
}
